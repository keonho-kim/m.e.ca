// Purpose: Publish a self-contained browser archive as one immutable generated Go input.
// Pattern: Deterministic archive builder with atomic publication.
// Usage: The UI source build packages gzip payloads and their manifest in one ZIP store.
// Related: devtools/cmd/uiassets/compression.go, internal/webui/bundle.go.
package main

import (
	"archive/zip"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

type asset struct {
	File  string `json:"file"`
	Type  string `json:"type"`
	ETag  string `json:"etag"`
	Bytes int    `json:"bytes"`
}

func packBundle(input, output, cache string) (int, error) {
	manifest := make(map[string]asset)
	payloads := make(map[string][]byte)
	err := filepath.WalkDir(input, func(path string, entry fs.DirEntry, err error) error {
		if err != nil || entry.IsDir() {
			return err
		}
		if !entry.Type().IsRegular() {
			return fmt.Errorf("browser asset must be a regular file: %s", path)
		}
		source, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		hash := sha256.Sum256(source)
		name := hex.EncodeToString(hash[:]) + ".gz"
		if _, exists := payloads[name]; !exists {
			payloads[name], err = compressedAsset(source, hash, filepath.Join(cache, name))
			if err != nil {
				return err
			}
		}
		relative, err := filepath.Rel(input, path)
		if err != nil {
			return err
		}
		manifest[filepath.ToSlash(relative)] = asset{File: name, Type: contentType(path), ETag: `W/"` + strings.TrimSuffix(name, ".gz") + `"`, Bytes: len(source)}
		return nil
	})
	if err != nil {
		return 0, err
	}
	if _, exists := manifest["index.html"]; !exists {
		return 0, errors.New("browser bundle requires index.html")
	}
	metadata, err := json.Marshal(manifest)
	if err != nil {
		return 0, err
	}
	if len(metadata) > 1<<20 {
		return 0, errors.New("browser manifest exceeds the runtime 1MiB limit")
	}
	payloads["manifest.json"] = metadata
	names := make([]string, 0, len(payloads))
	for name := range payloads {
		names = append(names, name)
	}
	slices.Sort(names)
	var archive bytes.Buffer
	writer := zip.NewWriter(&archive)
	for _, name := range names {
		entry, err := writer.CreateHeader(&zip.FileHeader{Name: name, Method: zip.Store})
		if err != nil {
			return 0, err
		}
		if _, err := entry.Write(payloads[name]); err != nil {
			return 0, err
		}
	}
	if err := writer.Close(); err != nil {
		return 0, err
	}
	generated := "// Code generated by devtools/cmd/uiassets; DO NOT EDIT.\n" +
		"// Purpose: Include one complete browser archive in immutable binary string storage.\n" +
		"// Pattern: Generated build input.\n" +
		"// Usage: webui.New opens this archive without copying its payload.\n" +
		"// Related: devtools/cmd/uiassets/bundle.go, internal/webui/bundle.go.\n" +
		"package webui\n\nfunc init() { packedBundle = " + strconv.QuoteToASCII(archive.String()) + " }\n"
	if err := atomicWrite(output, []byte(generated)); err != nil {
		return 0, err
	}
	if err := pruneCache(cache, payloads); err != nil {
		return len(manifest), fmt.Errorf("bundle published; gzip cache cleanup failed: %w", err)
	}
	return len(manifest), nil
}

func contentType(path string) string {
	switch strings.ToLower(filepath.Ext(path)) {
	case ".html":
		return "text/html; charset=utf-8"
	case ".js", ".mjs":
		return "text/javascript; charset=utf-8"
	case ".css":
		return "text/css; charset=utf-8"
	case ".json", ".map":
		return "application/json"
	case ".txt":
		return "text/plain; charset=utf-8"
	case ".svg":
		return "image/svg+xml"
	case ".png":
		return "image/png"
	case ".jpg", ".jpeg":
		return "image/jpeg"
	case ".webp":
		return "image/webp"
	case ".woff2":
		return "font/woff2"
	default:
		return "application/octet-stream"
	}
}
