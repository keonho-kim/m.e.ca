export type CopyKey = keyof typeof copy;
export function languageCode(value: string) {
  return value === 'auto'
    ? typeof navigator !== 'undefined' && navigator.language.startsWith('ko')
      ? 'ko'
      : 'en'
    : value;
}
export function useLocale() {
  const language = useAstryxLocale();
  return useCallback(
    (key: CopyKey) => copy[key][language.toLowerCase().startsWith('ko') ? 0 : 1],
    [language]
  );
}
